/** The ISO time `ms` milliseconds before NOW. */
function before(ms) {
	return new Date(NOW - ms).toISOString();
}

function block(key, version, integrity) {
	const name = packageName(key);
	return [
		`"${key}":`,
		`  version "${version}"`,
		`  resolved "https://registry.yarnpkg.com/${name}/-/${name.split('/').pop()}-${version}.tgz"`,
		`  integrity ${integrity}`
	].join('\n');
}

function lockfile(...blocks) {
	return `${HEADER}${blocks.join('\n\n')}\n`;
}

/** An npm v3 `packages` entry resolved from the npm registry. */
function npmPackage(name, version, integrity, extra = {}) {
	const resolved = `https://registry.npmjs.org/${name}/-/${name.split('/').pop()}-${version}.tgz`;
	return { version, resolved, integrity, license: 'MIT', ...extra };
}

/** An npm lockfile with the root entry plus `packages`. */
function npmLock(packages, { lockfileVersion = 3 } = {}) {
	const root = { name: 'fixture', version: '1.0.0' };
	const document = { name: 'fixture', version: '1.0.0', lockfileVersion, requires: true, packages: { '': root, ...packages } };
	return `${JSON.stringify(document, null, 2)}\n`;
}

/** A registry document holding one version of `name`. */
function registryDocument(name, version, integrity, time) {
	const manifest = { name, version, license: 'MIT', dist: { integrity } };
	return { name, versions: { [version]: manifest }, time: { created: OLD_TIME, [version]: time } };
}

/**
 * A stub registry: `table` maps `name@version` to an integrity (published long ago) or to
 * `{ integrity, time }`; anything else fails the lookup. Documents go through the real reader.
 */
function stub(table) {
	const calls = [];
	const lookup = async (name, version) => {
		calls.push(`${name}@${version}`);
		const row = Object.hasOwn(table, `${name}@${version}`) ? table[`${name}@${version}`] : undefined;
		if (row === undefined) throw new Error(`no such version ${name}@${version}`);
		const { integrity, time } = typeof row === 'string' ? { integrity: row, time: OLD_TIME } : row;
		return readRegistryDocument(registryDocument(name, version, integrity, time), version);
	};
	return { lookup, calls };
}

/** A lookup serving one hand-built registry document through the real reader. */
function documentLookup(document) {
	const calls = [];
	const lookup = async (name, version) => {
		calls.push(`${name}@${version}`);
		return readRegistryDocument(document, version);
	};
	return { lookup, calls };
}

async function unexpectedLookup(name, version) {
	throw new Error(`unexpected lookup of ${name}@${version}`);
}

/** Runs `main()` with a fixed clock and a lookup that fails unless one is given; collects its output. */
async function runMain(args, options = {}) {
	let stdout = '';
	let stderr = '';
	const out = { write: (text) => (stdout += text) };
	const err = { write: (text) => (stderr += text) };
	const status = await main(args, out, err, { now: () => NOW, lookup: unexpectedLookup, ...options });
	return { status, stdout, stderr, output: stdout + stderr };
}

/** Writes `files` ({ name: text }) to a temp folder removed after the test; returns their paths by name. */
function tempFiles(t, files) {
	const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'lock-review-'));
	t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
	return Object.fromEntries(
		Object.entries(files).map(([name, text]) => {
			const file = path.join(dir, name);
			fs.writeFileSync(file, text);
			return [name, file];
		})
	);
}

/** Writes the old and new lockfiles to a temp folder removed after the test. */
function lockPair(t, oldText, newText) {
	const { old, new: newFile } = tempFiles(t, { old: oldText, new: newText });
	return { oldFile: old, newFile };
}

function waiverFile(t, waivers) {
	return tempFiles(t, { 'waivers.json': JSON.stringify(waivers) })['waivers.json'];
}

function waiver(overrides = {}) {
	return {
		package: '@scope/pkg@2.0.0',
		fixes: 'GHSA-abcd-efgh-2345',
		reason: 'fixes a prototype pollution',
		diffReadBy: 'Vole',
		diffReadOn: '2026-10-25',
		...overrides
	};
}

