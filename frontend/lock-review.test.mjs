describe('the diff', () => {
	test('identical lockfiles have no removed or added blocks', () => {
		const text = lockfile(LEFT_PAD, SCOPED);
		const { removed, added } = diffLockfiles(text, text);
		assert.deepEqual([removed.length, added.length], [0, 0]);
	});

	test('a changed block counts as removed plus added', () => {
		const changed = block('left-pad@^1.3.0', '1.3.1', INTEGRITY_A);
		const { removed, added } = diffLockfiles(lockfile(LEFT_PAD), lockfile(changed));
		assert.deepEqual(removed.map((entry) => entry.version), ['1.3.0']);
		assert.deepEqual(added.map((entry) => entry.version), ['1.3.1']);
	});

	test('an alias key names the real package', () => {
		assert.equal(packageName('string-width-cjs@npm:string-width@^4.2.0'), 'string-width');
		assert.equal(packageName('alias@npm:@scope/real@^1'), '@scope/real');
		assert.equal(packageName('@scope/pkg@^2.0.0'), '@scope/pkg');
	});

	test('the registry URL is the full document, a scoped name encoded the way the registry expects', () => {
		assert.equal(registryDocumentUrl('@sveltejs/adapter-static'), 'https://registry.npmjs.org/@sveltejs%2fadapter-static');
		assert.equal(registryDocumentUrl('left-pad'), 'https://registry.npmjs.org/left-pad');
	});

	test('the registry URL refuses a name that fails the naming rule', () => {
		assert.throws(() => registryDocumentUrl('@scope/..'), GuardError);
		assert.throws(() => registryDocumentUrl('a b'), GuardError);
	});

	test('a file in neither format is refused', () => {
		assert.throws(() => diffLockfiles('left-pad@1.0.0:\n  version "1.0.0"\n', lockfile(LEFT_PAD)), /old lockfile: neither/);
	});
});

