describe('the imports', () => {
	/** Every module specifier `source` imports or re-exports, static or dynamic. */
	function specifiers(source) {
		return [...source.matchAll(/\b(?:from|import)\s*\(?\s*(['"])([^'"]+)\1/g)].map((match) => match[2]);
	}

	test('the driver set is exactly the three tools', () => {
		assert.deepEqual(new Set(DRIVER_FILES), new Set(['lock-review.mjs', 'install-check.mjs', 'licences.mjs']));
		assert.equal(DRIVER_FILES.length, 3);
	});

	for (const file of DRIVER_FILES) {
		test(`${file} imports only node built-ins and the driver files`, () => {
			const source = fs.readFileSync(path.join(FRONTEND, file), 'utf8');
			assert.doesNotMatch(source, /\bimport\s*\(\s*[^'"\s]/, 'a computed dynamic import');
			assert.doesNotMatch(source, /\bcreateRequire\b|\brequire\s*\(/, 'a CommonJS require');
			const found = specifiers(source);
			assert.ok(found.length > 0, `${file} has imports`);
			for (const specifier of found) {
				if (specifier.startsWith('node:')) continue;
				assert.ok(specifier.startsWith('./') || specifier.startsWith('../'), `${file}: a package import ${specifier}`);
				const target = path.relative(FRONTEND, path.resolve(FRONTEND, specifier));
				assert.ok(DRIVER_FILES.includes(target), `${file} imports ${specifier}, outside ${DRIVER_FILES.join(', ')}`);
			}
		});
	}
});

