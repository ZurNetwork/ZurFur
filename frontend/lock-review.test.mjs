describe('the review', () => {
	test('refuses a removed block under --no-removals', async () => {
		const { lookup } = stub({});
		const result = await reviewLockfiles(lockfile(LEFT_PAD, SCOPED), lockfile(SCOPED), { noRemovals: true, lookup });
		assert.deepEqual(result.errors, []);
		assert.deepEqual(result.findings.map((f) => f.rule), ['removal']);
	});

	test('lists a removed block without failing when removals are allowed', async () => {
		const { lookup } = stub({});
		const result = await reviewLockfiles(lockfile(LEFT_PAD, SCOPED), lockfile(SCOPED), { lookup });
		assert.equal(result.removed.length, 1);
		assert.deepEqual([result.findings, result.errors], [[], []]);
	});

	test('refuses an added block whose integrity differs from the registry', async () => {
		const { lookup, calls } = stub({ '@scope/pkg@2.0.0': INTEGRITY_B });
		const result = await reviewLockfiles(lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED), { lookup });
		assert.deepEqual(calls, ['@scope/pkg@2.0.0']);
		assert.deepEqual(result.errors, []);
		assert.deepEqual(result.findings.map((f) => f.rule), ['integrity']);
	});

	test('refuses an added block with no integrity', async () => {
		const bare = block('@scope/pkg@^2.0.0', '2.0.0', INTEGRITY_A).replace(/\n {2}integrity [^\n]*/, '');
		const { lookup } = stub({ '@scope/pkg@2.0.0': INTEGRITY_A });
		const result = await reviewLockfiles(lockfile(LEFT_PAD), lockfile(LEFT_PAD, bare), { lookup });
		assert.deepEqual(result.findings.map((f) => f.rule), ['integrity']);
	});

	test('passes an added block that matches the registry', async () => {
		const { lookup } = stub({ '@scope/pkg@2.0.0': INTEGRITY_A });
		const result = await reviewLockfiles(lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED), { noRemovals: true, lookup });
		assert.equal(result.added.length, 1);
		assert.deepEqual([result.findings, result.errors], [[], []]);
	});

	test('a failed lookup is an error, never a pass', async () => {
		const { lookup } = stub({});
		const result = await reviewLockfiles(lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED), { lookup });
		assert.equal(result.errors.length, 1);
		assert.match(result.errors[0], /lookup failed for @scope\/pkg@2\.0\.0/);
	});

	test('a lookup whose manifest has no dist.integrity is an error', async () => {
		const lookup = async () => ({ manifest: { name: '@scope/pkg', version: '2.0.0' }, published: new Date(OLD_TIME) });
		const result = await reviewLockfiles(lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED), { lookup });
		assert.match(result.errors.join('\n'), /no dist\.integrity/);
	});
});

describe('the age floor', () => {
	test('refuses a version published 6 days 23 hours ago', async () => {
		const { lookup } = stub({ '@scope/pkg@2.0.0': YOUNG });
		const result = await reviewLockfiles(lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED), { lookup, now: () => NOW, minAgeDays: 7 });
		assert.deepEqual(result.errors, []);
		assert.deepEqual(result.findings.map((f) => f.rule), ['young']);
		assert.match(result.findings[0].message, /^@scope\/pkg@2\.0\.0: published 2026-10-19T13:00:00\.000Z, 6\.9 days old/);
	});

	test('passes a version published 7 days and 1 minute ago', async () => {
		const { lookup } = stub({ '@scope/pkg@2.0.0': OLD_ENOUGH });
		const result = await reviewLockfiles(lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED), { lookup, now: () => NOW, minAgeDays: 7 });
		assert.deepEqual([result.findings, result.errors], [[], []]);
		assert.equal(result.ages[0].waiver, undefined);
	});

	test('without --min-age-days a young version is not refused', async () => {
		const { lookup } = stub({ '@scope/pkg@2.0.0': YOUNG });
		const result = await reviewLockfiles(lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED), { lookup, now: () => NOW });
		assert.deepEqual([result.findings, result.errors, result.ages], [[], [], [undefined]]);
	});

	test('a publish date that cannot be computed counts as young', async () => {
		const lookup = async () => ({ manifest: { dist: { integrity: INTEGRITY_A } }, published: new Date(Number.NaN) });
		const result = await reviewLockfiles(lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED), { lookup, now: () => NOW, minAgeDays: 7 });
		assert.deepEqual(result.findings.map((f) => f.rule), ['young']);
	});

	test('a CLI run prints each added entry with its publish date and age', async (t) => {
		const { oldFile, newFile } = lockPair(t, lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED));
		const run = await runMain([oldFile, newFile, '--min-age-days', '7'], { lookup: stub({ '@scope/pkg@2.0.0': YOUNG }).lookup });
		assert.equal(run.status, 1, run.output);
		assert.match(run.stdout, /^added: "@scope\/pkg@\^2\.0\.0" \(version 2\.0\.0\), published 2026-10-19T13:00:00\.000Z, 6\.9 days old$/m);
		assert.match(run.stdout, /^FAIL \[young\] @scope\/pkg@2\.0\.0: .*under the 7-day floor$/m);
	});

	test('a CLI run over the floor exits 0', async (t) => {
		const { oldFile, newFile } = lockPair(t, lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED));
		const run = await runMain([oldFile, newFile, '--min-age-days', '7'], { lookup: stub({ '@scope/pkg@2.0.0': OLD_ENOUGH }).lookup });
		assert.equal(run.status, 0, run.output);
		assert.match(run.stdout, /^ok: every added entry matches the registry, every one is at least 7 days old or waived$/m);
	});
});

describe('waivers', () => {
	test('an exact waiver passes a young entry and the output names its fix', async (t) => {
		const { oldFile, newFile } = lockPair(t, lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED));
		const waivers = waiverFile(t, { waivers: [waiver()] });
		const { lookup } = stub({ '@scope/pkg@2.0.0': YOUNG });
		const run = await runMain([oldFile, newFile, '--min-age-days', '7', '--waivers', waivers], { lookup });
		assert.equal(run.status, 0, run.output);
		assert.match(run.stdout, /^added: .*6\.9 days old, waived \(fixes GHSA-abcd-efgh-2345\)$/m);
	});

	test('a waiver for another version does not pass a young entry', async (t) => {
		const { oldFile, newFile } = lockPair(t, lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED));
		const waivers = waiverFile(t, { waivers: [waiver({ package: '@scope/pkg@2.0.1' })] });
		const { lookup } = stub({ '@scope/pkg@2.0.0': YOUNG });
		const run = await runMain([oldFile, newFile, '--min-age-days', '7', '--waivers', waivers], { lookup });
		assert.equal(run.status, 1, run.output);
		assert.match(run.stdout, /FAIL \[young\]/);
	});

	test('an integrity mismatch fails even under a waiver', async (t) => {
		const { oldFile, newFile } = lockPair(t, lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED));
		const waivers = waiverFile(t, { waivers: [waiver()] });
		const { lookup } = stub({ '@scope/pkg@2.0.0': { integrity: INTEGRITY_B, time: YOUNG.time } });
		const run = await runMain([oldFile, newFile, '--min-age-days', '7', '--waivers', waivers], { lookup });
		assert.equal(run.status, 1, run.output);
		assert.match(run.stdout, /FAIL \[integrity\]/);
		assert.doesNotMatch(run.stdout, /FAIL \[young\]/);
	});

	test('a waiver applies to the same version in an npm lockfile', async (t) => {
		const oldText = npmLock({});
		const newText = npmLock({ 'node_modules/@scope/pkg': npmPackage('@scope/pkg', '2.0.0', INTEGRITY_A) });
		const { oldFile, newFile } = lockPair(t, oldText, newText);
		const waivers = waiverFile(t, { waivers: [waiver()] });
		const { lookup } = stub({ '@scope/pkg@2.0.0': YOUNG });
		const run = await runMain([oldFile, newFile, '--min-age-days', '7', '--waivers', waivers], { lookup });
		assert.equal(run.status, 0, run.output);
		assert.match(run.stdout, /waived \(fixes GHSA-abcd-efgh-2345\)/);
	});
});

describe('the waiver file', () => {
	const refused = {
		'an extra key': { waivers: [{ ...waiver(), note: 'x' }] },
		'a range in package': { waivers: [waiver({ package: '@scope/pkg@^2.0.0' })] },
		'a package without a version': { waivers: [waiver({ package: '@scope/pkg' })] },
		'a package name failing the rule': { waivers: [waiver({ package: '_pkg@1.0.0' })] },
		'a missing fixes': { waivers: [(({ fixes, ...rest }) => rest)(waiver())] },
		'a fixes that is not a GHSA or CVE id': { waivers: [waiver({ fixes: 'GHSA-1234' })] },
		'an empty reason': { waivers: [waiver({ reason: '' })] },
		'an empty diffReadBy': { waivers: [waiver({ diffReadBy: ' ' })] },
		'a future diffReadOn': { waivers: [waiver({ diffReadOn: '2026-10-27' })] },
		'a diffReadOn that is not a real date': { waivers: [waiver({ diffReadOn: '2026-02-30' })] },
		'a duplicate package': { waivers: [waiver(), waiver({ fixes: 'CVE-2026-12345' })] },
		'a top-level key other than waivers': { waivers: [waiver()], extra: true },
		'waivers that is not an array': { waivers: waiver() },
		'a top level that is an array': [waiver()]
	};
	for (const [label, document] of Object.entries(refused)) {
		test(`refuses ${label} with exit 2, before any lookup`, async (t) => {
			const { oldFile, newFile } = lockPair(t, lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED));
			const waivers = waiverFile(t, document);
			const { lookup, calls } = stub({ '@scope/pkg@2.0.0': YOUNG });
			const run = await runMain([oldFile, newFile, '--min-age-days', '7', '--waivers', waivers], { lookup });
			assert.equal(run.status, 2, run.output);
			assert.deepEqual(calls, []);
			assert.match(run.stderr, /waivers\.json: /);
		});
	}

	test('accepts a GHSA and a CVE waiver read today', () => {
		const text = JSON.stringify({
			waivers: [waiver({ diffReadOn: '2026-10-26' }), waiver({ package: 'left-pad@1.3.0', fixes: 'CVE-2026-1234' })]
		});
		const table = parseWaivers(text, NOW);
		assert.deepEqual([...table.keys()], ['@scope/pkg@2.0.0', 'left-pad@1.3.0']);
	});

	test('a file that is not JSON is refused', () => {
		assert.throws(() => parseWaivers('{"waivers": [', NOW), GuardError);
	});
});

describe('fail-closed registry reads', () => {
	async function reviewWithDocument(t, document, newBlock = SCOPED) {
		const { oldFile, newFile } = lockPair(t, lockfile(LEFT_PAD), lockfile(LEFT_PAD, newBlock));
		const { lookup, calls } = documentLookup(document);
		const run = await runMain([oldFile, newFile, '--min-age-days', '7'], { lookup });
		return { run, calls };
	}

	test('a garbage publish time exits 2', async (t) => {
		const document = registryDocument('@scope/pkg', '2.0.0', INTEGRITY_A, 'last tuesday');
		const { run } = await reviewWithDocument(t, document);
		assert.equal(run.status, 2, run.output);
		assert.match(run.stderr, /is not a date/);
	});

	test('a publish time that is not ISO UTC exits 2', async (t) => {
		const document = registryDocument('@scope/pkg', '2.0.0', INTEGRITY_A, 'Mon, 01 Jan 2024 00:00:00 GMT');
		const { run } = await reviewWithDocument(t, document);
		assert.equal(run.status, 2, run.output);
	});

	test('version __proto__ exits 2 without a lookup', async (t) => {
		const document = registryDocument('@scope/pkg', '2.0.0', INTEGRITY_A, OLD_TIME);
		const { run, calls } = await reviewWithDocument(t, document, block('@scope/pkg@^2.0.0', '__proto__', INTEGRITY_A));
		assert.equal(run.status, 2, run.output);
		assert.deepEqual(calls, []);
		assert.match(run.stderr, /refused version "__proto__"/);
	});

	test('a version with a leading zero exits 2 without a lookup', async (t) => {
		const document = registryDocument('@scope/pkg', '2.0.0', INTEGRITY_A, OLD_TIME);
		const { run, calls } = await reviewWithDocument(t, document, block('@scope/pkg@^2.0.0', '02.0.0', INTEGRITY_A));
		assert.equal(run.status, 2, run.output);
		assert.deepEqual(calls, []);
	});

	test('a .. in the name exits 2 without a lookup', async (t) => {
		const document = registryDocument('@scope/..', '2.0.0', INTEGRITY_A, OLD_TIME);
		const { run, calls } = await reviewWithDocument(t, document, block('@scope/..@^2.0.0', '2.0.0', INTEGRITY_A));
		assert.equal(run.status, 2, run.output);
		assert.deepEqual(calls, []);
		assert.match(run.stderr, /refused package name "@scope\/\.\."/);
	});

	test('an inherited time key exits 2', async (t) => {
		const document = registryDocument('@scope/pkg', '2.0.0', INTEGRITY_A, OLD_TIME);
		document.time = Object.create({ '2.0.0': OLD_TIME });
		const { run } = await reviewWithDocument(t, document);
		assert.equal(run.status, 2, run.output);
	});

	test('an inherited versions key exits 2', async (t) => {
		const document = registryDocument('@scope/pkg', '2.0.0', INTEGRITY_A, OLD_TIME);
		document.versions = Object.create(document.versions);
		const { run } = await reviewWithDocument(t, document);
		assert.equal(run.status, 2, run.output);
	});

	test('a time or version found only on Object.prototype is not the document own', () => {
		const document = registryDocument('@scope/pkg', '1.0.0', INTEGRITY_A, OLD_TIME);
		const manifest = { dist: { integrity: INTEGRITY_A } };
		Object.defineProperty(Object.prototype, '2.0.0', { value: OLD_TIME, configurable: true, writable: true });
		try {
			assert.throws(() => readRegistryDocument(document, '2.0.0'), /no versions\["2\.0\.0"\]/);
			document.versions['2.0.0'] = manifest;
			assert.throws(() => readRegistryDocument(document, '2.0.0'), /no time\["2\.0\.0"\]/);
		} finally {
			delete Object.prototype['2.0.0'];
		}
	});

	test('versions or time that is not a plain object exits 2', () => {
		const document = registryDocument('@scope/pkg', '2.0.0', INTEGRITY_A, OLD_TIME);
		assert.throws(() => readRegistryDocument({ ...document, time: [OLD_TIME] }, '2.0.0'), /no time object/);
		assert.throws(() => readRegistryDocument({ ...document, versions: 'x' }, '2.0.0'), /no versions object/);
		assert.throws(() => readRegistryDocument([document], '2.0.0'), /not an object/);
	});

	test('a failed lookup exits 2', async (t) => {
		const { oldFile, newFile } = lockPair(t, lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED));
		const run = await runMain([oldFile, newFile, '--min-age-days', '7'], { lookup: stub({}).lookup });
		assert.equal(run.status, 2, run.output);
		assert.match(run.stderr, /lookup failed for @scope\/pkg@2\.0\.0/);
	});

	test('the registry lookup fetches the full document once and reads it', async (t) => {
		const realFetch = globalThis.fetch;
		t.after(() => (globalThis.fetch = realFetch));
		const urls = [];
		globalThis.fetch = async (url) => {
			urls.push(String(url));
			return Response.json(registryDocument('@scope/pkg', '2.0.0', INTEGRITY_A, OLD_TIME));
		};
		const { manifest, published } = await registryLookup('@scope/pkg', '2.0.0');
		assert.deepEqual(urls, ['https://registry.npmjs.org/@scope%2fpkg']);
		assert.equal(manifest.dist.integrity, INTEGRITY_A);
		assert.equal(published.toISOString(), OLD_TIME);
	});

	test('the registry lookup refuses a redirect, so the review exits 2', async (t) => {
		const realFetch = globalThis.fetch;
		t.after(() => (globalThis.fetch = realFetch));
		const inits = [];
		globalThis.fetch = async (url, init) => {
			inits.push(init);
			if (init?.redirect === 'error') throw new TypeError('fetch failed: unexpected redirect');
			return Response.json(registryDocument('@scope/pkg', '2.0.0', INTEGRITY_A, OLD_TIME));
		};
		const { oldFile, newFile } = lockPair(t, lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED));
		const run = await runMain([oldFile, newFile, '--min-age-days', '7'], { lookup: registryLookup });
		assert.equal(run.status, 2, run.output);
		assert.equal(inits.length, 1);
		assert.equal(inits[0].redirect, 'error');
		assert.ok(inits[0].signal instanceof AbortSignal);
	});

	test('the registry lookup refuses an HTTP error', async (t) => {
		const realFetch = globalThis.fetch;
		t.after(() => (globalThis.fetch = realFetch));
		globalThis.fetch = async () => new Response('gone', { status: 404 });
		await assert.rejects(registryLookup('@scope/pkg', '2.0.0'), /HTTP 404/);
	});
});

describe('the npm v3 reader', () => {
	async function reviewNpm(t, oldPackages, newPackages, options = {}) {
		const { oldFile, newFile } = lockPair(t, npmLock(oldPackages), options.newText ?? npmLock(newPackages));
		const { lookup, calls } = stub(options.table ?? {});
		const run = await runMain([oldFile, newFile, '--min-age-days', '7'], { lookup });
		return { run, calls };
	}

	const PKG = npmPackage('@scope/pkg', '2.0.0', INTEGRITY_A);
	const refused = {
		'a link entry': { 'node_modules/@scope/pkg': { ...PKG, link: true } },
		'a bundled entry': { 'node_modules/@scope/pkg': { ...PKG, inBundle: true } },
		'an entry without integrity': { 'node_modules/@scope/pkg': (({ integrity, ...rest }) => rest)(PKG) },
		'a foreign resolved': { 'node_modules/@scope/pkg': { ...PKG, resolved: 'https://evil.example/pkg-2.0.0.tgz' } },
		'a resolved that only starts like the registry': {
			'node_modules/@scope/pkg': { ...PKG, resolved: 'https://registry.npmjs.org.evil.example/pkg.tgz' }
		},
		'an entry outside node_modules': { 'packages/pkg': PKG },
		'an entry that is not an object': { 'node_modules/@scope/pkg': 'x' }
	};
	for (const [label, packages] of Object.entries(refused)) {
		test(`refuses ${label} with exit 2`, async (t) => {
			const { run, calls } = await reviewNpm(t, {}, packages, { table: { '@scope/pkg@2.0.0': INTEGRITY_A } });
			assert.equal(run.status, 2, run.output);
			assert.deepEqual(calls, []);
			assert.match(run.stderr, /new lockfile: packages\[/);
		});
	}

	test('refuses lockfileVersion 2 with exit 2', async (t) => {
		const newText = npmLock({ 'node_modules/@scope/pkg': PKG }, { lockfileVersion: 2 });
		const { run } = await reviewNpm(t, {}, {}, { newText });
		assert.equal(run.status, 2, run.output);
		assert.match(run.stderr, /lockfileVersion 2, not 3/);
	});

	test('refuses a yarn file against an npm file with exit 2', async (t) => {
		const { oldFile, newFile } = lockPair(t, lockfile(LEFT_PAD), npmLock({ 'node_modules/@scope/pkg': PKG }));
		const run = await runMain([oldFile, newFile]);
		assert.equal(run.status, 2, run.output);
		assert.match(run.stderr, /old lockfile is yarn and the new one npm/);
	});

	test('skips the root entry', () => {
		assert.deepEqual(parseNpmLockfile(npmLock({})), []);
	});

	test('lists and age-checks an entry added with a new version', async (t) => {
		const oldPackages = { 'node_modules/@scope/pkg': npmPackage('@scope/pkg', '1.0.0', INTEGRITY_B) };
		const newPackages = { 'node_modules/@scope/pkg': PKG };
		const { run, calls } = await reviewNpm(t, oldPackages, newPackages, { table: { '@scope/pkg@2.0.0': YOUNG } });
		assert.equal(run.status, 1, run.output);
		assert.deepEqual(calls, ['@scope/pkg@2.0.0']);
		assert.match(run.stdout, /^removed: @scope\/pkg@1\.0\.0 at "node_modules\/@scope\/pkg"$/m);
		assert.match(run.stdout, /^added: @scope\/pkg@2\.0\.0 at "node_modules\/@scope\/pkg", published .*, 6\.9 days old$/m);
		assert.match(run.stdout, /^1 removed, 1 added$/m);
		assert.match(run.stdout, /^FAIL \[young\] @scope\/pkg@2\.0\.0: /m);
	});

	test('the name comes from the entry name when present, else the key', async (t) => {
		const newPackages = {
			'node_modules/alias': npmPackage('real-pkg', '1.0.0', INTEGRITY_A, { name: 'real-pkg' }),
			'node_modules/outer/node_modules/@scope/inner': npmPackage('@scope/inner', '3.0.0', INTEGRITY_A)
		};
		const table = { 'real-pkg@1.0.0': INTEGRITY_A, '@scope/inner@3.0.0': INTEGRITY_A };
		const { run, calls } = await reviewNpm(t, {}, newPackages, { table });
		assert.equal(run.status, 0, run.output);
		assert.deepEqual(calls.toSorted(), ['@scope/inner@3.0.0', 'real-pkg@1.0.0']);
	});

	test('one triple at two paths is one added entry with one lookup', async (t) => {
		const newPackages = {
			'node_modules/@scope/pkg': PKG,
			'node_modules/other/node_modules/@scope/pkg': PKG
		};
		const { run, calls } = await reviewNpm(t, {}, newPackages, { table: { '@scope/pkg@2.0.0': INTEGRITY_A } });
		assert.equal(run.status, 0, run.output);
		assert.deepEqual(calls, ['@scope/pkg@2.0.0']);
		assert.match(run.stdout, /^0 removed, 1 added$/m);
	});

	test('an unchanged triple is neither removed nor added', () => {
		const text = npmLock({ 'node_modules/@scope/pkg': PKG });
		const moved = npmLock({ 'node_modules/x/node_modules/@scope/pkg': PKG });
		const { removed, added } = diffLockfiles(text, moved);
		assert.deepEqual([removed.length, added.length], [0, 0]);
	});

	test('a changed integrity is removed plus added', () => {
		const oldText = npmLock({ 'node_modules/@scope/pkg': npmPackage('@scope/pkg', '2.0.0', INTEGRITY_B) });
		const { removed, added } = diffLockfiles(oldText, npmLock({ 'node_modules/@scope/pkg': PKG }));
		assert.deepEqual([removed.map((entry) => entry.integrity), added.map((entry) => entry.integrity)], [[INTEGRITY_B], [INTEGRITY_A]]);
	});

	test('a JSON file that does not parse is refused', () => {
		assert.throws(() => diffLockfiles('{ "lockfileVersion": 3', '{}'), /old lockfile: not valid JSON/);
	});
});

