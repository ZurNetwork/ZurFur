// Tests for the lockfile review, offline: every registry lookup is stubbed.
//   node --test frontend/lock-review.test.mjs

import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { describe, test } from 'node:test';
import { fileURLToPath } from 'node:url';
import { diffLockfiles, packageName, registryUrl, reviewLockfiles } from './lock-review.mjs';

const FRONTEND = path.dirname(fileURLToPath(import.meta.url));
const SCRIPT = path.join(FRONTEND, 'lock-review.mjs');
const BASE_LOCK_FILE = [path.join(FRONTEND, 'web', 'yarn.lock'), path.join(FRONTEND, 'yarn.lock')].find((file) =>
	fs.existsSync(file)
);

const HEADER = '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n';
const INTEGRITY_A = 'sha512-AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA==';
const INTEGRITY_B = 'sha512-BBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBBB==';
const ADAPTER_STATIC_INTEGRITY =
	'sha512-7D9lYFWJmB7zxZyTE/qxjksvMqzMuYrrsyh1f4AlZqeZeACPRySjbC3aFiY55wb1tWUaKOQG9PVbm74JcN2Iew==';
const ADAPTER_STATIC_BLOCK = [
	'"@sveltejs/adapter-static@^3.0.10":',
	'  version "3.0.10"',
	'  resolved "https://registry.yarnpkg.com/@sveltejs/adapter-static/-/adapter-static-3.0.10.tgz#526ab78cd1d3a861dd0233e8ff34a204af40d595"',
	`  integrity ${ADAPTER_STATIC_INTEGRITY}`
].join('\n');

function block(key, version, integrity) {
	const name = packageName(key);
	return [
		`"${key}":`,
		`  version "${version}"`,
		`  resolved "https://registry.yarnpkg.com/${name}/-/${name.split('/').pop()}-${version}.tgz"`,
		`  integrity ${integrity}`
	].join('\n');
}

function lockfile(...blocks) {
	return `${HEADER}${blocks.join('\n\n')}\n`;
}

/** A stub registry: `table` maps `name@version` to an integrity; anything else fails the lookup. */
function stub(table) {
	const calls = [];
	const lookup = async (name, version) => {
		calls.push(`${name}@${version}`);
		const integrity = table[`${name}@${version}`];
		if (integrity === undefined) throw new Error(`no such version ${name}@${version}`);
		return integrity;
	};
	return { lookup, calls };
}

const LEFT_PAD = block('left-pad@^1.3.0', '1.3.0', INTEGRITY_A);
const SCOPED = block('@scope/pkg@^2.0.0', '2.0.0', INTEGRITY_A);

describe('the diff', () => {
	test('identical lockfiles have no removed or added blocks', () => {
		const text = lockfile(LEFT_PAD, SCOPED);
		const { removed, added } = diffLockfiles(text, text);
		assert.deepEqual([removed.length, added.length], [0, 0]);
	});

	test('a changed block counts as removed plus added', () => {
		const changed = block('left-pad@^1.3.0', '1.3.1', INTEGRITY_A);
		const { removed, added } = diffLockfiles(lockfile(LEFT_PAD), lockfile(changed));
		assert.deepEqual(removed.map((b) => b.fields.get('version')), ['1.3.0']);
		assert.deepEqual(added.map((b) => b.fields.get('version')), ['1.3.1']);
	});

	test('an alias key names the real package', () => {
		assert.equal(packageName('string-width-cjs@npm:string-width@^4.2.0'), 'string-width');
		assert.equal(packageName('alias@npm:@scope/real@^1'), '@scope/real');
		assert.equal(packageName('@scope/pkg@^2.0.0'), '@scope/pkg');
	});

	test('a scoped name is encoded the way the registry expects', () => {
		assert.equal(
			registryUrl('@sveltejs/adapter-static', '3.0.10'),
			'https://registry.npmjs.org/@sveltejs%2fadapter-static/3.0.10'
		);
		assert.equal(registryUrl('left-pad', '1.3.0'), 'https://registry.npmjs.org/left-pad/1.3.0');
	});
});

describe('the review', () => {
	test('refuses a removed block under --no-removals', async () => {
		const { lookup } = stub({});
		const result = await reviewLockfiles(lockfile(LEFT_PAD, SCOPED), lockfile(SCOPED), { noRemovals: true, lookup });
		assert.deepEqual(result.errors, []);
		assert.deepEqual(result.findings.map((f) => f.rule), ['removal']);
	});

	test('lists a removed block without failing when removals are allowed', async () => {
		const { lookup } = stub({});
		const result = await reviewLockfiles(lockfile(LEFT_PAD, SCOPED), lockfile(SCOPED), { lookup });
		assert.equal(result.removed.length, 1);
		assert.deepEqual([result.findings, result.errors], [[], []]);
	});

	test('refuses an added block whose integrity differs from the registry', async () => {
		const { lookup, calls } = stub({ '@scope/pkg@2.0.0': INTEGRITY_B });
		const result = await reviewLockfiles(lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED), { lookup });
		assert.deepEqual(calls, ['@scope/pkg@2.0.0']);
		assert.deepEqual(result.errors, []);
		assert.deepEqual(result.findings.map((f) => f.rule), ['integrity']);
	});

	test('refuses an added block with no integrity', async () => {
		const bare = block('@scope/pkg@^2.0.0', '2.0.0', INTEGRITY_A).replace(/\n {2}integrity [^\n]*/, '');
		const { lookup } = stub({ '@scope/pkg@2.0.0': INTEGRITY_A });
		const result = await reviewLockfiles(lockfile(LEFT_PAD), lockfile(LEFT_PAD, bare), { lookup });
		assert.deepEqual(result.findings.map((f) => f.rule), ['integrity']);
	});

	test('passes an added block that matches the registry', async () => {
		const { lookup } = stub({ '@scope/pkg@2.0.0': INTEGRITY_A });
		const result = await reviewLockfiles(lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED), { noRemovals: true, lookup });
		assert.equal(result.added.length, 1);
		assert.deepEqual([result.findings, result.errors], [[], []]);
	});

	test('a failed lookup is an error, never a pass', async () => {
		const { lookup } = stub({});
		const result = await reviewLockfiles(lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED), { lookup });
		assert.equal(result.errors.length, 1);
		assert.match(result.errors[0], /lookup failed for @scope\/pkg@2\.0\.0/);
	});
});

function runCli(args, stubTable) {
	const env = { ...process.env };
	delete env.LOCK_REVIEW_REGISTRY_STUB;
	if (stubTable !== undefined) {
		const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'lock-review-stub-'));
		const file = path.join(dir, 'registry.json');
		fs.writeFileSync(file, JSON.stringify(stubTable));
		env.LOCK_REVIEW_REGISTRY_STUB = file;
		try {
			return spawnSync(process.execPath, [SCRIPT, ...args], { encoding: 'utf8', env });
		} finally {
			fs.rmSync(dir, { recursive: true, force: true });
		}
	}
	return spawnSync(process.execPath, [SCRIPT, ...args], { encoding: 'utf8', env });
}

/** Writes the old and new lockfiles to a temp folder removed after the test. */
function lockPair(t, oldText, newText) {
	const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'lock-review-'));
	t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
	const oldFile = path.join(dir, 'old.lock');
	const newFile = path.join(dir, 'new.lock');
	fs.writeFileSync(oldFile, oldText);
	fs.writeFileSync(newFile, newText);
	return { oldFile, newFile };
}

describe('the CLI', () => {
	for (const args of [[], ['one.lock'], ['a', 'b', 'c'], ['a', 'b', '--bogus'], ['--help']]) {
		test(`exits 2 on bad usage ${JSON.stringify(args)}`, () => {
			const run = runCli(args, {});
			assert.equal(run.status, 2, run.stdout + run.stderr);
			assert.match(run.stderr, /usage:/);
		});
	}

	test('exits 2 on an unreadable lockfile', (t) => {
		const { oldFile } = lockPair(t, lockfile(LEFT_PAD), lockfile(LEFT_PAD));
		const run = runCli([oldFile, path.join(path.dirname(oldFile), 'missing.lock')], {});
		assert.equal(run.status, 2, run.stdout + run.stderr);
	});

	test('exits 1 on a removed block under --no-removals', (t) => {
		const { oldFile, newFile } = lockPair(t, lockfile(LEFT_PAD, SCOPED), lockfile(SCOPED));
		const run = runCli([oldFile, newFile, '--no-removals'], {});
		assert.equal(run.status, 1, run.stdout + run.stderr);
		assert.match(run.stdout, /FAIL \[removal\]/);
	});

	test('exits 1 on an integrity mismatch', (t) => {
		const { oldFile, newFile } = lockPair(t, lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED));
		const run = runCli([oldFile, newFile], { '@scope/pkg@2.0.0': INTEGRITY_B });
		assert.equal(run.status, 1, run.stdout + run.stderr);
		assert.match(run.stdout, /FAIL \[integrity\]/);
	});

	test('exits 2 on a failed lookup', (t) => {
		const { oldFile, newFile } = lockPair(t, lockfile(LEFT_PAD), lockfile(LEFT_PAD, SCOPED));
		const run = runCli([oldFile, newFile], {});
		assert.equal(run.status, 2, run.stdout + run.stderr);
		assert.match(run.stderr, /lookup failed/);
	});

	test('proves the workspace move: zero removals and one matching added block', (t) => {
		const base = fs.readFileSync(BASE_LOCK_FILE, 'utf8');
		const withoutAdapter = base.replace(`${ADAPTER_STATIC_BLOCK}\n\n`, '');
		const anchor = withoutAdapter.indexOf('"@sveltejs/kit@');
		assert.ok(anchor > 0, 'the base lockfile has @sveltejs/kit');
		const moved = `${withoutAdapter.slice(0, anchor)}${ADAPTER_STATIC_BLOCK}\n\n${withoutAdapter.slice(anchor)}`;
		const { oldFile, newFile } = lockPair(t, withoutAdapter, moved);
		const run = runCli([oldFile, newFile, '--no-removals'], {
			'@sveltejs/adapter-static@3.0.10': ADAPTER_STATIC_INTEGRITY
		});
		assert.equal(run.status, 0, run.stdout + run.stderr);
		assert.match(run.stdout, /^0 removed, 1 added$/m);
		assert.match(run.stdout, /^added: "@sveltejs\/adapter-static@\^3\.0\.10" \(version 3\.0\.10\)$/m);
		assert.match(run.stderr, /using the registry stub/);
	});
});
