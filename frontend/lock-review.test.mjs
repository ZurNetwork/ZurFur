/** Writes a licence list (MIT only unless given) to a temp folder removed after the test; returns its path. */
function listFile(t, text = licenceList()) {
	return tempFiles(t, { 'npm-licences.json': text })['npm-licences.json'];
}

/** Runs `main()` with a fixed clock and a lookup that fails unless one is given; collects its output. */
async function runMain(args, options = {}) {
	let stdout = '';
	let stderr = '';
	const out = { write: (text) => (stdout += text) };
	const err = { write: (text) => (stderr += text) };
	const status = await main(args, out, err, { now: () => NOW, lookup: unexpectedLookup, versionLookup: unexpectedLookup, ...options });
	return { status, stdout, stderr, output: stdout + stderr };
}

/** Writes `files` ({ name: text }) to a temp folder removed after the test; returns their paths by name. */
function tempFiles(t, files) {
	const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'lock-review-'));
	t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
	return Object.fromEntries(
		Object.entries(files).map(([name, text]) => {
			const file = path.join(dir, name);
			fs.writeFileSync(file, text);
			return [name, file];
		})
	);
}

/** Writes the old and new lockfiles to a temp folder removed after the test. */
function lockPair(t, oldText, newText) {
	const { old, new: newFile } = tempFiles(t, { old: oldText, new: newText });
	return { oldFile: old, newFile };
}

function waiverFile(t, waivers) {
	return tempFiles(t, { 'waivers.json': JSON.stringify(waivers) })['waivers.json'];
}

function waiver(overrides = {}) {
	return {
		package: '@scope/pkg@2.0.0',
		fixes: 'GHSA-abcd-efgh-2345',
		reason: 'fixes a prototype pollution',
		diffReadBy: 'Vole',
		diffReadOn: '2026-10-25',
		...overrides
	};
}

