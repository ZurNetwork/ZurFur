import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import additions from '../../lib/styles/tokens.additions.json';
import tokens from '../../lib/styles/tokens.json';
import {
	generateTokensCss,
	isAllowedFamilyList,
	isAllowedValue,
	type GenerateOutcome,
	type GenerateRefusalReason
} from './generate';

const committed = readFileSync(new URL('../../lib/styles/tokens.css', import.meta.url), 'utf8');

function cssOrFail(outcome: GenerateOutcome): string {
	if (outcome.kind === 'refused') throw new Error(JSON.stringify(outcome.refusals));
	return outcome.css;
}

const real = cssOrFail(generateTokensCss(tokens, additions));

/** The blank-line separated sections of the generated text, in order. */
const sections = real.split('\n\n');

/** The `--name: value;` lines of a section, indentation dropped. */
function declarationsOf(section: string | undefined): readonly string[] {
	return (section ?? '')
		.split('\n')
		.map((line) => line.trim())
		.filter((line) => line.startsWith('--') || line.startsWith('color-scheme'));
}

const namesOf = (lines: readonly string[]): readonly string[] =>
	lines.map((line) => line.slice(0, line.indexOf(':')));

describe('the committed tokens.css', () => {
	it('is the generated text, byte for byte', () => {
		expect(committed).toBe(real);
	});

	it('has the nine parts in order', () => {
		const openers = sections.map((section) => section.split('\n')[0]);
		expect(openers).toEqual([
			'/* Generated by `yarn tokens` from tokens.json and tokens.additions.json; never edit by hand. */',
			":root, [data-skin='dark'] {",
			"[data-skin='light'] {",
			'@media (prefers-color-scheme: light) {',
			':root {',
			':root {',
			'@media (prefers-reduced-motion: reduce) {',
			"[data-motion='still'] {",
			"[data-motion='still'],"
		]);
	});

	it('declares the same names in both skin blocks', () => {
		const dark = namesOf(declarationsOf(sections[1]));
		const light = namesOf(declarationsOf(sections[2]));
		expect(dark.length).toBeGreaterThan(60);
		expect(light).toEqual(dark);
	});

	it('declares every colour and shadow token in each skin block, unskinned and aliases included', () => {
		const dark = namesOf(declarationsOf(sections[1]));
		for (const id of ['color', 'shadow'] as const) {
			for (const entry of tokens[id].tokens) expect(dark).toContain(`--${entry.name}`);
		}
	});

	it('writes the light body of the attribute block and of the media query the same', () => {
		expect(declarationsOf(sections[3])).toEqual(declarationsOf(sections[2]));
		expect(sections[3]).toContain(":root:not([data-skin='dark'])");
		expect(sections[1]).toContain('color-scheme: dark;');
		expect(sections[2]).toContain('color-scheme: light;');
	});

	it('writes a reference as a var() and a plain value as it stands', () => {
		const dark = declarationsOf(sections[1]);
		const light = declarationsOf(sections[2]);
		expect(dark).toContain('--color-sheet: var(--color-surface);');
		expect(light).toContain('--color-sheet: var(--color-surface-raised);');
		expect(dark).toContain('--color-bg: #151417;');
		expect(light).toContain('--color-bg: #ece5d3;');
	});

	it('gives each skin block the plain name of every dark/light pair', () => {
		for (const [index, skin] of [
			[1, 'dark'],
			[2, 'light'],
			[3, 'light']
		] as const) {
			const lines = declarationsOf(sections[index]);
			expect(lines).toContain(`--space-peek-offset: var(--space-peek-offset-${skin});`);
			expect(lines).toContain(`--size-peek-step: var(--size-peek-step-${skin});`);
		}
		expect(declarationsOf(sections[4])).toContain('--space-peek-offset-dark: 6px;');
	});

	it('starts each font family with the one Fontsource registers', () => {
		const lines = declarationsOf(sections[4]);
		const ui = lines.find((line) => line.startsWith('--font-ui:'));
		const mono = lines.find((line) => line.startsWith('--font-mono:'));
		expect(
			ui?.startsWith(
				'--font-ui: "Atkinson Hyperlegible Next Variable", "Atkinson Hyperlegible Next", '
			)
		).toBe(true);
		expect(
			mono?.startsWith(
				'--font-mono: "Atkinson Hyperlegible Mono Variable", "Atkinson Hyperlegible Mono", '
			)
		).toBe(true);
	});

	it('holds the easing from the additions beside the design system ones', () => {
		expect(declarationsOf(sections[4])).toContain('--easing-linear: linear;');
	});

	it('writes no sound and no type style', () => {
		expect(real).not.toContain('--sound-');
		expect(real).not.toContain('--type-');
		expect(real).not.toContain('triangle');
	});

	it('keeps rise and sink out of the plain block and with the durations', () => {
		expect(declarationsOf(sections[4]).join('\n')).not.toMatch(/--space-(rise|sink)/);
		expect(declarationsOf(sections[5]).slice(-2)).toEqual([
			'--space-rise: 1px;',
			'--space-sink: 1px;'
		]);
		expect(
			declarationsOf(sections[5]).filter((line) => line.startsWith('--duration-'))
		).toHaveLength(18);
	});
});

const MOTION = [
	'fast',
	'base',
	'slow',
	'slide',
	'note-pop',
	'note-up',
	'page-in',
	'page-under',
	'page-out',
	'dim',
	'spring',
	'hello',
	'burst',
	'hop'
].map((name) => `--duration-${name}: 0ms;`);

describe('the motion stops', () => {
	it('zero exactly the fourteen motion durations, rise and sink under reduced motion', () => {
		expect(declarationsOf(sections[6])).toEqual([
			...MOTION,
			'--space-rise: 0px;',
			'--space-sink: 0px;'
		]);
	});

	it('zero the same and the page fade under Still', () => {
		const expected = [
			...MOTION,
			'--duration-page-fade: 0ms;',
			'--space-rise: 0px;',
			'--space-sink: 0px;'
		];
		expect(declarationsOf(sections[7]).toSorted()).toEqual(expected.toSorted());
	});

	it('never zero a lifetime or the hold, nor the page fade under reduced motion', () => {
		for (const section of [sections[6], sections[7]]) {
			expect(section).not.toContain('toast-life');
			expect(section).not.toContain('status-life');
			expect(section).not.toContain('duration-hold');
		}
		expect(sections[6]).not.toContain('page-fade');
		expect(sections[7]).toContain('--duration-page-fade: 0ms;');
	});

	it('stops animation and transition under Still with one important rule over six selectors', () => {
		expect(sections[8]).toBe(
			[
				"[data-motion='still'],",
				"[data-motion='still']::before,",
				"[data-motion='still']::after,",
				"[data-motion='still'] *,",
				"[data-motion='still'] *::before,",
				"[data-motion='still'] *::after {",
				'\tanimation: none !important;',
				'\ttransition: none !important;',
				'}',
				''
			].join('\n')
		);
	});

	it('names no lively mode anywhere', () => {
		expect(real).not.toContain("data-motion='lively'");
		expect(real).not.toContain('data-motion="lively"');
		expect(real).not.toContain('lively');
	});

	it('hands the lively durations to :root alone, in and out of the reduced-motion query', () => {
		expect(sections[5]).toContain('--duration-fast: 100ms;');
		expect(sections[6]?.split('\n').at(1)).toBe('\t:root {');
	});
});

