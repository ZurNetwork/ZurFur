type Fields = Record<string, unknown>;

const token = (name: string, value: unknown): Fields => ({
	name,
	value,
	usage: 'Used for a test.'
});
const group = (...entries: Fields[]): Fields => ({ tokens: entries });

/** A small valid token file, with the two motion spaces and two durations; overrides replace sections. */
function fixture(over: Fields = {}): Fields {
	return {
		name: 'Test',
		version: 1,
		color: {
			themes: [
				{ id: 'dark', name: 'Dark' },
				{ id: 'light', name: 'Light' }
			],
			tokens: [token('color-bg', { dark: '#000000', light: '#ffffff' })]
		},
		type: {
			fonts: [],
			families: { ui: '"A B", sans-serif', mono: '"C D", monospace' },
			groups: []
		},
		spacing: group(token('space-rise', '1px'), token('space-sink', '1px')),
		duration: group(token('duration-fast', '100ms'), token('duration-hold', '900ms')),
		sound: group(token('sound-open', 'triangle 660Hz')),
		...over
	};
}

function reasonsOf(outcome: GenerateOutcome): readonly GenerateRefusalReason[] {
	return outcome.kind === 'refused' ? outcome.refusals.map((refusal) => refusal.reason) : [];
}

function refusalsFor(over: Fields, extra: Fields = {}): readonly GenerateRefusalReason[] {
	return reasonsOf(generateTokensCss(fixture(over), extra));
}

describe('the fixture', () => {
	it('is accepted', () => {
		expect(generateTokensCss(fixture(), {}).kind).toBe('generated');
	});
});

describe('refusals', () => {
	it.each([
		['an uppercase function', 'URL(x)'],
		['a lowercase function', 'url(x)'],
		['image-set', 'image-set("https://a.test/x" 1x)'],
		['a comment opener', 'red /*'],
		['an important flag', 'red !important'],
		['a newline between words', 'red\nblue'],
		['a trailing newline', 'red\n'],
		['a tab between words', 'red\tblue'],
		['a semicolon', 'red; color: blue'],
		['a quote', '"red"'],
		['a calc()', 'calc(1px + 2px)'],
		['a var() written out', 'var(--x)'],
		['an rgb() holding a function', 'rgb(var(--x), 0, 0)'],
		['a cubic-bezier() with three numbers', 'cubic-bezier(0, 0, 1)'],
		['nothing', ''],
		['a backslash', 'red\\'],
		['a url in text', 'https://a.test/x'],
		['a leading comma', ', red']
	])('turn away a value with %s', (_label, value) => {
		expect(refusalsFor({ radius: group(token('radius-a', value)) })).toEqual([
			'value-off-allow-list'
		]);
	});

	it('turn away an off-list value in either skin of a colour', () => {
		const colour = {
			themes: [
				{ id: 'dark', name: 'Dark' },
				{ id: 'light', name: 'Light' }
			],
			tokens: [token('color-bg', { dark: '#000000', light: 'URL(x)' })]
		};
		expect(refusalsFor({ color: colour })).toEqual(['value-off-allow-list']);
	});

	it('turn away a bad name', () => {
		expect(refusalsFor({ radius: group(token('x;y', '1px')) })).toEqual(['bad-name']);
	});

	it('turn away a reference inside a longer value', () => {
		expect(refusalsFor({ radius: group(token('radius-a', 'calc({color-bg} + 1px)')) })).toEqual([
			'embedded-reference'
		]);
	});

	it('turn away a dangling reference', () => {
		expect(refusalsFor({ radius: group(token('radius-a', '{missing}')) })).toContain(
			'dangling-reference'
		);
	});

	it('turn away a cyclic reference', () => {
		const over = {
			radius: group(token('radius-a', '{radius-b}'), token('radius-b', '{radius-a}'))
		};
		expect(refusalsFor(over)).toContain('cyclic-reference');
	});

	it('turn away a skinned value that lacks a skin', () => {
		const colour = {
			themes: [
				{ id: 'dark', name: 'Dark' },
				{ id: 'light', name: 'Light' }
			],
			tokens: [token('color-bg', { dark: '#000000' })]
		};
		expect(refusalsFor({ color: colour })).toEqual(['missing-skin']);
	});

	it('turn away a skinned value keyed by an unknown theme', () => {
		const colour = {
			themes: [
				{ id: 'dark', name: 'Dark' },
				{ id: 'light', name: 'Light' }
			],
			tokens: [token('color-bg', { dark: '#000000', light: '#ffffff', sepia: '#aa8800' })]
		};
		expect(refusalsFor({ color: colour })).toEqual(['unknown-theme']);
	});

	it('turn away a duration that has no class', () => {
		const over = {
			duration: group(token('duration-fast', '100ms'), token('duration-mystery', '5ms'))
		};
		expect(refusalsFor(over)).toEqual(['unclassified-duration']);
	});

	it('turn away an addition the token file already has', () => {
		const clash = { easing: group(token('easing-spring', 'linear')) };
		const outcome = generateTokensCss(tokens, clash);
		expect(reasonsOf(outcome)).toEqual(['addition-exists']);
	});

	it('turn away an addition that repeats another addition', () => {
		const twice = {
			easing: group(token('easing-linear', 'linear'), token('easing-linear', 'linear'))
		};
		expect(refusalsFor({}, twice)).toEqual(['addition-exists']);
	});

	it('turn away a value that differs by skin outside colour and shadow', () => {
		const over = { radius: group(token('radius-a', { dark: '1px', light: '2px' })) };
		expect(refusalsFor(over)).toEqual(['skinned-outside-skin-blocks']);
	});

	it('turn away a group it has no place for', () => {
		expect(refusalsFor({ weird: group(token('weird-a', '1px')) })).toEqual(['unknown-group']);
	});

	it('turn away a file without the motion spaces', () => {
		expect(refusalsFor({ spacing: group(token('space-1', '4px')) })).toEqual([
			'missing-token',
			'missing-token'
		]);
	});

	it('turn away a font family list off the allow-list', () => {
		const type = {
			fonts: [],
			families: { ui: 'sans-serif; color: red', mono: 'monospace' },
			groups: []
		};
		expect(refusalsFor({ type })).toEqual(['bad-font-family']);
	});

	it('turn away a skinned alias name a token already has', () => {
		const over = {
			spacing: group(
				token('space-rise', '1px'),
				token('space-sink', '1px'),
				token('space-gap-dark', '6px'),
				token('space-gap-light', '4px'),
				token('space-gap', '5px')
			)
		};
		expect(refusalsFor(over)).toEqual(['alias-collision']);
	});

	it('turn away a token that takes the name of a font variable', () => {
		expect(refusalsFor({ radius: group(token('font-ui', '1px')) })).toEqual(['duplicate-name']);
	});

	it('name every refusal of one kind at once', () => {
		const over = {
			radius: group(token('x;y', '1px'), token('radius-a', 'calc({color-bg})'))
		};
		expect(refusalsFor(over)).toEqual(['bad-name', 'embedded-reference']);
		const later = {
			radius: group(token('radius-a', 'URL(x)')),
			duration: group(token('duration-mystery', '5ms'))
		};
		expect(refusalsFor(later)).toEqual(['value-off-allow-list', 'unclassified-duration']);
	});

	it.each([[undefined], [7], ['text'], [[]]])(
		'turn away %j in place of the files without throwing',
		(input) => {
			expect(reasonsOf(generateTokensCss(input, {}))).toEqual(['malformed']);
			expect(reasonsOf(generateTokensCss(fixture(), input))).toEqual(['malformed']);
		}
	);

	it('writes a derived alias for a pair only when both halves exist', () => {
		const over = {
			spacing: group(
				token('space-rise', '1px'),
				token('space-sink', '1px'),
				token('space-lone-dark', '6px')
			)
		};
		const css = cssOrFail(generateTokensCss(fixture(over), {}));
		expect(css).not.toContain('--space-lone:');
	});
});

describe('the allow-list', () => {
	it.each([
		['a hex colour', '#abc'],
		['a hex colour with alpha', '#aabbccdd'],
		['a length', '12px'],
		['a negative rem', '-0.5rem'],
		['a percentage', '26%'],
		['an angle', '45deg'],
		['a bare number', '400'],
		['a keyword', 'none'],
		['a shadow list', 'inset 0 1px 0 rgba(239, 217, 168, 0.09), 0 1px 2px #00000066'],
		['a cubic-bezier()', 'cubic-bezier(0.34, 1.56, 0.64, 1)'],
		['an rgb()', 'rgb(1, 2, 3)']
	])('lets through %s', (_label, value) => {
		expect(isAllowedValue(value)).toBe(true);
	});

	it('lets through a font family list with quoted names', () => {
		expect(
			isAllowedFamilyList('"Atkinson Hyperlegible Mono", ui-monospace, "SF Mono", monospace')
		).toBe(true);
		expect(isAllowedFamilyList('"a;b", serif')).toBe(false);
		expect(isAllowedFamilyList('serif\nsans-serif')).toBe(false);
	});

	it('answers a long near-miss quickly', () => {
		const started = performance.now();
		expect(isAllowedValue(`${'a '.repeat(20000)}!`)).toBe(false);
		expect(isAllowedValue(`${'1px, '.repeat(20000)}!`)).toBe(false);
		expect(performance.now() - started).toBeLessThan(2000);
	});
});
