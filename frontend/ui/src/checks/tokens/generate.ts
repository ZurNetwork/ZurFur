import { MOTION_ATTRIBUTE, SKIN_ATTRIBUTE, type Skin } from '../../lib/styles/environment.ts';
import {
	isAllowedFamilyList,
	isAllowedValue,
	parseTokenModel,
	valueIn,
	type ModelRefusalReason,
	type Refusal,
	type Token,
	type TokenGroup,
	type TokenModel,
	type TokenValue
} from '../../lib/styles/token-model.ts';

/** Why the generator turned the token files away, on top of the model's reasons. */
export type GenerateRefusalReason =
	| ModelRefusalReason
	| 'bad-font-family'
	| 'skinned-outside-skin-blocks'
	| 'unclassified-duration'
	| 'unknown-group'
	| 'missing-token'
	| 'alias-collision';

export type GenerateRefusal = Refusal<GenerateRefusalReason>;

/** The stylesheet text, or every reason the token files were turned away. */
export type GenerateOutcome =
	| { readonly kind: 'generated'; readonly css: string }
	| { readonly kind: 'refused'; readonly refusals: readonly GenerateRefusal[] };

// ---------------------------------------------------------------------------
// What each group becomes.
// ---------------------------------------------------------------------------

/** The groups that wear a skin: redeclared, name for name, in each skin block. */
const SKIN_GROUPS: readonly string[] = ['color', 'shadow'];

/** The groups written once under `:root`, in the order they are written. */
const PLAIN_GROUPS: readonly string[] = [
	'text',
	'leading',
	'weight',
	'spacing',
	'radius',
	'size',
	'breakpoint',
	'blur',
	'layer',
	'easing'
];

const DURATION_GROUP = 'duration';

/** Fontsource's registered family for each of the design system's two font families. */
const FONTSOURCE_FAMILY = {
	ui: 'Atkinson Hyperlegible Next Variable',
	mono: 'Atkinson Hyperlegible Mono Variable'
} as const;

/** The two spacings that move things and so stop with the motion. */
const MOTION_SPACES: readonly string[] = ['space-rise', 'space-sink'];

/** How a duration behaves when motion is reduced or stopped. */
type DurationClass = 'motion' | 'page-fade' | 'lifetime';

const MOTION_DURATIONS: readonly string[] = [
	'fast',
	'base',
	'slow',
	'slide',
	'note-pop',
	'note-up',
	'page-in',
	'page-under',
	'page-out',
	'dim',
	'spring',
	'hello',
	'burst',
	'hop'
];

const LIFETIME_DURATIONS: readonly string[] = ['toast-life', 'status-life', 'hold'];

const DURATION_CLASSES: ReadonlyMap<string, DurationClass> = new Map<string, DurationClass>([
	...MOTION_DURATIONS.map((name): [string, DurationClass] => [`duration-${name}`, 'motion']),
	['duration-page-fade', 'page-fade'],
	...LIFETIME_DURATIONS.map((name): [string, DurationClass] => [`duration-${name}`, 'lifetime'])
]);

const ZERO_TIME = '0ms';
const ZERO_LENGTH = '0px';

const HEADER =
	'/* Generated by `yarn tokens` from tokens.json and tokens.additions.json; never edit by hand. */';

function cssValue(value: TokenValue): string {
	return value.kind === 'reference' ? `var(--${value.name})` : value.text;
}

function declaration(name: string, value: string): string {
	return `--${name}: ${value};`;
}

/** One rule; each declaration is indented one level deeper than its selector. */
function rule(selector: string, declarations: readonly string[], depth: number): string {
	const outer = '\t'.repeat(depth);
	const inner = '\t'.repeat(depth + 1);
	const body = declarations.map((line) => `${inner}${line}`);
	return [`${outer}${selector} {`, ...body, `${outer}}`].join('\n');
}

function refuse(reason: GenerateRefusalReason, where: string, detail: string): GenerateRefusal {
	return { reason, where, detail };
}

/** The literal texts of a token, with where each sits, for the allow-list. */
function literalsOf(token: Token): readonly { readonly where: string; readonly text: string }[] {
	switch (token.values.kind) {
		case 'single':
			return token.values.value.kind === 'literal'
				? [{ where: token.name, text: token.values.value.text }]
				: [];
		case 'skinned':
			return [
				{ where: `${token.name}.dark`, value: token.values.dark },
				{ where: `${token.name}.light`, value: token.values.light }
			].flatMap(({ where, value }) =>
				value.kind === 'literal' ? [{ where, text: value.text }] : []
			);
	}
}

function checkAllowList(token: Token, refusals: GenerateRefusal[]): void {
	for (const { where, text } of literalsOf(token)) {
		if (!isAllowedValue(text)) {
			refusals.push(refuse('value-off-allow-list', where, `"${text}" is not on the allow-list`));
		}
	}
}

/** The groups the generator writes, each with the way it is written. */
function groupsByRole(
	model: TokenModel,
	refusals: GenerateRefusal[]
): ReadonlyMap<string, TokenGroup> {
	const byId = new Map<string, TokenGroup>();
	for (const group of model.groups) {
		const isKnown =
			SKIN_GROUPS.includes(group.id) ||
			PLAIN_GROUPS.includes(group.id) ||
			group.id === DURATION_GROUP;
		if (isKnown) byId.set(group.id, group);
		else
			refusals.push(refuse('unknown-group', group.id, 'the generator has no place for this group'));
	}
	return byId;
}

function tokensOf(groups: ReadonlyMap<string, TokenGroup>, id: string): readonly Token[] {
	return groups.get(id)?.tokens ?? [];
}

/** Each `X-dark` / `X-light` pair of tokens, as the stem X. */
function skinnedStems(tokens: readonly Token[]): readonly string[] {
	const names = new Set<string>(tokens.map((token) => token.name));
	return tokens.flatMap((token) => {
		if (!token.name.endsWith('-dark')) return [];
		const stem = token.name.slice(0, -'-dark'.length);
		return names.has(`${stem}-light`) ? [stem] : [];
	});
}

/** The declarations of one skin block: every colour and shadow token, then the skinned aliases. */
function skinDeclarations(
	skin: Skin,
	skinTokens: readonly Token[],
	stems: readonly string[]
): readonly string[] {
	const tokens = skinTokens.map((token) =>
		declaration(token.name, cssValue(valueIn(token.values, skin)))
	);
	const aliases = stems.map((stem) => declaration(stem, `var(--${stem}-${skin})`));
	return [...tokens, ...aliases];
}

function motionClassOf(token: Token): DurationClass | undefined {
	return DURATION_CLASSES.get(token.name);
}

function fontDeclarations(model: TokenModel, refusals: GenerateRefusal[]): readonly string[] {
	const { ui, mono } = model.type.families;
	const lists = [
		{ name: 'font-ui', fontsource: FONTSOURCE_FAMILY.ui, families: ui },
		{ name: 'font-mono', fontsource: FONTSOURCE_FAMILY.mono, families: mono }
	];
	return lists.flatMap(({ name, fontsource, families }) => {
		if (!isAllowedFamilyList(families)) {
			refusals.push(
				refuse(
					'bad-font-family',
					`type.families.${name}`,
					`"${families}" is not a font family list`
				)
			);
			return [];
		}
		return [declaration(name, `"${fontsource}", ${families}`)];
	});
}

function plainTokens(groups: ReadonlyMap<string, TokenGroup>): readonly Token[] {
	return PLAIN_GROUPS.flatMap((id) => tokensOf(groups, id)).filter(
		(token) => !MOTION_SPACES.includes(token.name)
	);
}

function plainDeclaration(token: Token, refusals: GenerateRefusal[]): readonly string[] {
	if (token.values.kind === 'skinned') {
		refusals.push(
			refuse(
				'skinned-outside-skin-blocks',
				token.name,
				'only colour and shadow tokens may differ by skin'
			)
		);
		return [];
	}
	return [declaration(token.name, cssValue(token.values.value))];
}

function render(model: TokenModel): GenerateOutcome {
	const refusals: GenerateRefusal[] = [];
	const groups = groupsByRole(model, refusals);
	const skinTokens = SKIN_GROUPS.flatMap((id) => tokensOf(groups, id));
	const plain = plainTokens(groups);
	const durations = tokensOf(groups, DURATION_GROUP);
	const spaces = MOTION_SPACES.flatMap((name) => {
		const found = tokensOf(groups, 'spacing').find((token) => token.name === name);
		if (found === undefined)
			refusals.push(refuse('missing-token', name, 'the motion stops need this token'));
		return found === undefined ? [] : [found];
	});
	const emitted = [...skinTokens, ...plain, ...durations, ...spaces];
	for (const token of emitted) checkAllowList(token, refusals);

	const stems = skinnedStems(emitted);
	const taken = new Set<string>([...emitted.map((token) => token.name), 'font-ui', 'font-mono']);
	for (const stem of stems) {
		if (taken.has(stem))
			refusals.push(refuse('alias-collision', stem, 'a token already has the skinned alias name'));
	}
	for (const name of ['font-ui', 'font-mono']) {
		if (emitted.some((token) => token.name === name)) {
			refusals.push(
				refuse('duplicate-name', name, 'the font variables are written by the generator')
			);
		}
	}

	const durationDeclarations = durations.flatMap((token) => {
		if (motionClassOf(token) === undefined) {
			refusals.push(
				refuse(
					'unclassified-duration',
					token.name,
					'name the duration in a class: motion, page fade or lifetime'
				)
			);
		}
		return plainDeclaration(token, refusals);
	});
	const spaceDeclarations = spaces.flatMap((token) => plainDeclaration(token, refusals));
	const plainDeclarations = [
		...fontDeclarations(model, refusals),
		...plain.flatMap((token) => plainDeclaration(token, refusals))
	];

	const motionNames = durations
		.filter((token) => motionClassOf(token) === 'motion')
		.map((token) => token.name);
	const stillNames = durations
		.filter((token) => ['motion', 'page-fade'].includes(motionClassOf(token) ?? ''))
		.map((token) => token.name);
	const zeroed = (names: readonly string[]): readonly string[] => [
		...names.map((name) => declaration(name, ZERO_TIME)),
		...MOTION_SPACES.map((name) => declaration(name, ZERO_LENGTH))
	];

	if (refusals.length > 0) return { kind: 'refused', refusals };

	const darkBody = skinDeclarations('dark', skinTokens, stems);
	const lightBody = skinDeclarations('light', skinTokens, stems);
	const skinSelector = (skin: Skin): string => `[${SKIN_ATTRIBUTE}='${skin}']`;
	const still = `[${MOTION_ATTRIBUTE}='still']`;
	const stopSelectors = [
		still,
		`${still}::before`,
		`${still}::after`,
		`${still} *`,
		`${still} *::before`,
		`${still} *::after`
	];
	const sections = [
		HEADER,
		rule(`:root, ${skinSelector('dark')}`, ['color-scheme: dark;', ...darkBody], 0),
		rule(skinSelector('light'), ['color-scheme: light;', ...lightBody], 0),
		[
			'@media (prefers-color-scheme: light) {',
			rule(`:root:not(${skinSelector('dark')})`, ['color-scheme: light;', ...lightBody], 1),
			'}'
		].join('\n'),
		rule(':root', plainDeclarations, 0),
		rule(':root', [...durationDeclarations, ...spaceDeclarations], 0),
		['@media (prefers-reduced-motion: reduce) {', rule(':root', zeroed(motionNames), 1), '}'].join(
			'\n'
		),
		rule(still, zeroed(stillNames), 0),
		rule(
			stopSelectors.join(',\n'),
			['animation: none !important;', 'transition: none !important;'],
			0
		)
	];
	return { kind: 'generated', css: `${sections.join('\n\n')}\n` };
}

/**
 * Turns the parsed `tokens.json` and `tokens.additions.json` into the text of
 * `tokens.css`, or returns every reason they were turned away. It never throws.
 */
export function generateTokensCss(tokens: unknown, additions: unknown): GenerateOutcome {
	const parsed = parseTokenModel(tokens, additions);
	switch (parsed.kind) {
		case 'refused':
			return { kind: 'refused', refusals: parsed.refusals };
		case 'parsed':
			return render(parsed.model);
	}
}

/** One refusal as a plain line for a terminal. */
export function describeRefusal(refusal: GenerateRefusal): string {
	return `${refusal.reason}: ${refusal.where}: ${refusal.detail}`;
}
