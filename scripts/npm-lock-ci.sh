#!/bin/sh
# The body of CI's npm-lock job: the advisory check, and the 7-day floor and
# the licence rule over frontend/yarn.lock and lexicons/package-lock.json, with
# the BASE commit's tools and data, so a change can't loosen the checks that
# judge it.
#
#   sh npm-lock-ci.sh <base-sha> <block|report>
#
# Runs from the checkout's root as its current directory, usually as the base
# commit's copy extracted to a temp folder. Env: GITHUB_EVENT_NAME.
#
# The base is verified first: on a pull_request or a push, HEAD^1 must be it;
# on a merge_group, it must be an ancestor of HEAD. A malformed SHA, a missing
# base commit, any other event or a mismatch exits 1.
#
# Every path read from the base must be a regular file (mode 100644) under
# plain folders there, or the run exits 1 naming it and its mode. This
# change's own copies of the same paths, the ones the next run reads from it as
# its base, must each be absent or a regular file under plain folders at HEAD;
# anything else (a symlink, an executable, a gitlink, a folder, a symlinked
# folder) is a finding (exit 1), and the other checks still run.
#
# The tools (npm-advisories.sh, lock-review.mjs, install-check.mjs,
# licences.mjs) come as one set from the base; only a base without this driver
# gives the change's own set, read from HEAD, with a warning. The data:
#   - the old lockfiles: the base's frontend/yarn.lock, else its
#     frontend/web/yarn.lock, else an empty yarn v1 file; the base's
#     lexicons/package-lock.json, else an empty npm v3 file;
#   - the waivers: the base's lock-age-waivers.json, else HEAD's, with a
#     warning;
#   - the licence list: from wherever the tools came from. With the base's
#     tools, the base's npm-licences.json, and a base without one exits 1;
#     with the change's, HEAD's, with a warning;
#   - each lockfile's advisory ignores: the base's file when the change alters
#     that lockfile and the base has one, otherwise the change's, so a new or
#     renewed acceptance lands in a change that adds no package.
# The change's own files the checks didn't use are still checked: when either
# ignore file came from the base, both of the change's go through the advisory
# tool's allow-list (--allow-list-only); when HEAD's waivers differ from the
# base's, lock-review parses them over an empty diff; when HEAD's licence list
# differs from the base's, lock-review sweeps every entry of both lockfiles
# against it. Both lists are read from HEAD's blobs, never the working tree,
# and one that isn't a regular file at HEAD gets only its finding. A file the
# change deletes fails there. The floors and the waivers parse are given the
# chosen licence list.
# The advisory check and the allow-list run in <mode> (report demotes an
# advisory to a warning); the floors, the waivers parse, the sweep and the
# read-set check always block. Every check runs even after one fails, and the
# worst (highest) exit code wins.
set -u

# The tools, as repo-relative paths, all taken from one source.
TOOLS="scripts/npm-advisories.sh frontend/lock-review.mjs frontend/install-check.mjs frontend/licences.mjs"
# The data a run reads from its base.
DATA="frontend/yarn.lock frontend/web/yarn.lock lexicons/package-lock.json lock-age-waivers.json npm-licences.json osv-scanner.frontend.toml osv-scanner.lexicons.toml"
# Every path a run reads from its base: this driver, the tools and the data.
READ_SET="scripts/npm-lock-ci.sh $TOOLS $DATA"
EMPTY_YARN_LOCK='# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1'
EMPTY_NPM_LOCK='{"lockfileVersion": 3, "packages": {"": {}}}'

say() { printf 'npm-lock: %s\n' "$*"; }
warn() { printf '::warning::npm-lock: %s\n' "$*"; }
err() { printf '::error::npm-lock: %s\n' "$*"; }
fail() {
    err "$*"
    exit 1
}

work=""
cleanup() { [ -n "$work" ] && rm -rf "$work"; }
trap cleanup EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM

if [ "$#" -ne 2 ]; then
    echo "usage: npm-lock-ci.sh <base-sha> <block|report>" >&2
    exit 2
fi
base="$1"
mode="$2"
case "$mode" in
    block | report) ;;
    *)
        echo "usage: npm-lock-ci.sh <base-sha> <block|report>" >&2
        exit 2
        ;;
esac

# --- the base ---------------------------------------------------------------------

if ! printf '%s' "$base" | grep -qE '^[0-9a-f]{40}$'; then
    fail "the base SHA '$base' is not 40 lowercase hex digits"
fi
if ! git cat-file -e "$base^{commit}" 2>/dev/null; then
    fail "the base commit $base is not in this checkout"
fi
event="${GITHUB_EVENT_NAME:-}"
case "$event" in
    pull_request | push)
        parent1="$(git rev-parse --verify --quiet 'HEAD^1')" || parent1=""
        if [ "$parent1" != "$base" ]; then
            fail "HEAD^1 ($parent1) is not the base $base"
        fi
        say "base verified: HEAD^1 is $base"
        ;;
    merge_group)
        if ! git merge-base --is-ancestor "$base" HEAD 2>/dev/null; then
            fail "the merge group's base $base is not an ancestor of HEAD"
        fi
        say "base verified: $base is an ancestor of HEAD"
        ;;
    *) fail "not a pull request, a merge group or a push (GITHUB_EVENT_NAME '$event')" ;;
esac

if ! work="$(mktemp -d)"; then
    fail "can't create a temp folder"
fi
mkdir "$work/tools" "$work/data" "$work/head" || fail "can't create folders in $work"

worst=0
# record <check> <code>: reports <code> and raises worst.
record() {
    say "$1: exit $2"
    if [ "$2" -gt "$worst" ]; then worst="$2"; fi
}

# entry_at <rev> <path>: sets present to 1 when <rev> holds <path>, and
# problem to what makes it unsafe to read (a parent that is neither absent nor
# a folder, or an entry that is not a regular file), else to empty; returns 1
# when the tree can't be read.
entry_at() {
    problem=""
    present=0
    parent="$2"
    while :; do
        case "$parent" in
            */*) parent="${parent%/*}" ;;
            *) break ;;
        esac
        listing="$(git ls-tree --full-tree "$1" -- "$parent")" || return 1
        case "$listing" in
            "" | "040000 tree "*) ;;
            *)
                problem="$parent is mode ${listing%% *}, not a folder (040000)"
                return 0
                ;;
        esac
    done
    listing="$(git ls-tree --full-tree "$1" -- "$2")" || return 1
    case "$listing" in
        "") ;;
        "100644 blob "*) present=1 ;;
        *)
            present=1
            problem="$2 is mode ${listing%% *}, not a regular file (100644)"
            ;;
    esac
}

# base_has <path>: whether the base holds <path>, one of READ_SET; a failed
# read, or a <path> that isn't a regular file under plain folders there, exits 1.
base_has() {
    case " $READ_SET " in
        *" $1 "*) ;;
        *) fail "$1 is not in the driver's read set" ;;
    esac
    entry_at "$base" "$1" || fail "can't read the base's tree at $1"
    if [ -n "$problem" ]; then
        fail "the base's $problem"
    fi
    [ "$present" = 1 ]
}

# from_base <path> <dest>: writes the base's <path> to <dest>, or exits 1.
from_base() {
    base_has "$1" || fail "the base has no $1"
    git show "$base:$1" >"$2" || fail "can't read $1 from the base"
}

# head_copy <path>: sets own to a temp path holding HEAD's <path> when that is
# a regular file (a path that doesn't exist when HEAD has none), and own_ok to
# 0 when HEAD's <path> is anything else.
head_copy() {
    own="$work/head/$(printf '%s' "$1" | tr / _)"
    own_ok=1
    entry_at HEAD "$1" || fail "can't read HEAD's tree at $1"
    if [ -n "$problem" ]; then
        own_ok=0
    elif [ "$present" = 1 ]; then
        git show "HEAD:$1" >"$own" || fail "can't read $1 from HEAD"
    fi
}

# --- this change's own read set -----------------------------------------------------

# What the next run reads from this change as its base: each path absent, or a
# regular file under plain folders, at HEAD.
reported="|"
for path in $READ_SET; do
    entry_at HEAD "$path" || fail "can't read HEAD's tree at $path"
    if [ -n "$problem" ]; then
        case "$reported" in
            *"|$problem|"*) continue ;;
        esac
        reported="$reported$problem|"
        err "this change's $problem"
        record "this change's $path" 1
    fi
done

# --- the tools: one set, from one source --------------------------------------

if base_has scripts/npm-lock-ci.sh; then
    tool_source=base
else
    tool_source=change
    warn "the base has no scripts/npm-lock-ci.sh; using this change's own tools"
fi
tools="$work/tools"
for tool in $TOOLS; do
    mkdir -p "$tools/$(dirname "$tool")" || fail "can't create a folder for $tool"
    if [ "$tool_source" = base ]; then
        from_base "$tool" "$tools/$tool"
    else
        head_copy "$tool"
        if [ "$own_ok" != 1 ] || [ ! -f "$own" ]; then
            fail "this change has no regular file $tool to run"
        fi
        cp "$own" "$tools/$tool" || fail "can't copy this change's $tool"
    fi
    say "tool $tool: from the $tool_source"
done

# --- the data ---------------------------------------------------------------------

# old_lockfile <name> <empty content> <path…>: sets picked to the first of the
# base's <path…> it holds, else to a file holding <empty content>.
old_lockfile() {
    name="$1"
    empty="$2"
    shift 2
    picked="$work/data/old-$name"
    for path in "$@"; do
        if base_has "$path"; then
            from_base "$path" "$picked"
            say "old $name lockfile: the base's $path"
            return
        fi
    done
    printf '%s\n' "$empty" >"$picked" || fail "can't write $picked"
    say "old $name lockfile: empty (the base has none)"
}

# ignores <name> <lockfile> <old lockfile> <ignore file>: sets picked to the
# base's <ignore file> when this change alters <lockfile> and the base has it,
# otherwise to this change's.
ignores() {
    if ! cmp -s "$3" "$2" && base_has "$4"; then
        picked="$work/data/$4"
        from_base "$4" "$picked"
        base_ignores=1
        say "$1 ignores: the base's $4 ($2 changed)"
    else
        picked="$4"
        say "$1 ignores: this change's $4"
    fi
}

old_lockfile frontend "$EMPTY_YARN_LOCK" frontend/yarn.lock frontend/web/yarn.lock
old_frontend="$picked"
old_lockfile lexicons "$EMPTY_NPM_LOCK" lexicons/package-lock.json
old_lexicons="$picked"
base_ignores=0
# The waivers: the base's, else HEAD's.
head_copy lock-age-waivers.json
own_waivers="$own"
own_waivers_ok="$own_ok"
if base_has lock-age-waivers.json; then
    waivers="$work/data/lock-age-waivers.json"
    from_base lock-age-waivers.json "$waivers"
    say "data lock-age-waivers.json: from the base"
else
    waivers="$own_waivers"
    warn "the base has no lock-age-waivers.json; using this change's"
fi
# The licence list: no fallback from the base's to the change's.
head_copy npm-licences.json
own_licences="$own"
own_licences_ok="$own_ok"
if [ "$tool_source" = base ]; then
    if ! base_has npm-licences.json; then
        fail "the base has scripts/npm-lock-ci.sh but no npm-licences.json, so no licence list to judge this change by"
    fi
    licences="$work/data/npm-licences.json"
    from_base npm-licences.json "$licences"
    say "data npm-licences.json: from the base"
else
    licences="$own_licences"
    warn "the base has no scripts/npm-lock-ci.sh; using this change's npm-licences.json"
fi
ignores frontend frontend/yarn.lock "$old_frontend" osv-scanner.frontend.toml
frontend_ignores="$picked"
ignores lexicons lexicons/package-lock.json "$old_lexicons" osv-scanner.lexicons.toml
lexicons_ignores="$picked"

# --- the checks -------------------------------------------------------------------

say "advisories ($mode)"
env -i PATH=/usr/bin:/bin HOME="${HOME:-/nonexistent}" NPM_ADVISORIES_MODE="$mode" \
    sh "$tools/scripts/npm-advisories.sh" \
    --frontend-config "$frontend_ignores" --lexicons-config "$lexicons_ignores"
record advisories "$?"

# The change's own ignore files, when the scan used a base's instead.
if [ "$base_ignores" = 1 ]; then
    say "the allow-list over this change's own ignore files ($mode)"
    env -i PATH=/usr/bin:/bin HOME="${HOME:-/nonexistent}" NPM_ADVISORIES_MODE="$mode" \
        sh "$tools/scripts/npm-advisories.sh" --allow-list-only \
        --frontend-config osv-scanner.frontend.toml --lexicons-config osv-scanner.lexicons.toml
    record "allow-list of this change's ignore files" "$?"
fi

node_bin="$(command -v node)" || node_bin=""
case "$node_bin" in
    /*) node_dir="$(dirname "$node_bin")" ;;
    *) node_bin="" ;;
esac

# floor <name> <old lockfile> <new lockfile>: the 7-day floor and the licence
# rule over one lockfile, under a clean environment holding only PATH (node's
# own folder first) and HOME.
floor() {
    say "floor over $3"
    if [ -z "$node_bin" ]; then
        say "no node on PATH"
        record "floor $1" 2
        return
    fi
    env -i PATH="$node_dir:/usr/bin:/bin" HOME="${HOME:-/nonexistent}" \
        "$node_bin" "$tools/frontend/lock-review.mjs" "$2" "$3" \
        --licences "$licences" \
        --min-age-days 7 --waivers "$waivers"
    record "floor $1" "$?"
}
floor frontend "$old_frontend" frontend/yarn.lock
floor lexicons "$old_lexicons" lexicons/package-lock.json

# The change's own waivers, HEAD's copy, when they differ from the base's the
# floor used: lock-review parses them over an empty diff, under the floor's
# environment.
if [ "$own_waivers_ok" = 1 ] && [ "$waivers" != "$own_waivers" ] && ! cmp -s "$waivers" "$own_waivers"; then
    say "this change's lock-age-waivers.json differs from the base's; parsing it"
    if [ -z "$node_bin" ]; then
        say "no node on PATH"
        record "this change's waivers" 2
    else
        env -i PATH="$node_dir:/usr/bin:/bin" HOME="${HOME:-/nonexistent}" \
            "$node_bin" "$tools/frontend/lock-review.mjs" "$old_frontend" "$old_frontend" \
            --licences "$licences" \
            --min-age-days 7 --waivers "$own_waivers"
        record "this change's waivers" "$?"
    fi
fi

# The change's own licence list, HEAD's copy, when it differs from the base's
# the floors used (or is deleted): the base's lock-review sweeps every entry of
# both lockfiles against it, under the floor's environment.
if [ "$own_licences_ok" = 1 ] && [ "$licences" != "$own_licences" ] && ! cmp -s "$licences" "$own_licences"; then
    say "this change's npm-licences.json differs from the base's; sweeping both lockfiles against it"
    if [ -z "$node_bin" ]; then
        say "no node on PATH"
        record "this change's licence list" 2
    else
        env -i PATH="$node_dir:/usr/bin:/bin" HOME="${HOME:-/nonexistent}" \
            "$node_bin" "$tools/frontend/lock-review.mjs" --licence-sweep --licences "$own_licences" frontend/yarn.lock lexicons/package-lock.json
        record "this change's licence list" "$?"
    fi
fi

say "worst exit: $worst"
exit "$worst"
