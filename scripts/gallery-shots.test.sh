# walk_case <name> <setup command> <expected text, or "pass">: --update over a
# reference folder holding one story folder after <setup> ran in it.
walk_case() {
    fresh
    mkdir -p "$shots/__screenshots__/button--primary"
    (cd "$shots/__screenshots__/button--primary" && eval "$2")
    run_script stubs-podman run --update
    if [ "$3" = pass ]; then
        if [ "$code" = 0 ]; then ok "$1"; else fail "$1" "exit $code; $out"; fi
    elif [ "$code" = 1 ] && printf '%s\n' "$out" | grep -qF -- "$3"; then
        ok "$1"
    else
        fail "$1" "exit $code; $out"
    fi
}
prefix="refused frontend/ui/shots/__screenshots__/button--primary"
