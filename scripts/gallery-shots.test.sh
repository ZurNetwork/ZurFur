    repo="$(cd "$work/repo" && pwd -P)"
    shots="$repo/frontend/ui/shots"
}

# run_script <stubs> <args…>: runs the copy under test with a clean environment
# (PLAYWRIGHT_IMAGE from $pin unless $pin is "unset", plus $extra_env); sets
# $out (stdout and stderr) and $code.
pin="$good_pin"
extra_env=""
run_script() {
    stubs="$1"
    shift
    if [ "$pin" = unset ]; then
        set -- "PATH=$work/$stubs:$work/tools" HOME="$work" $extra_env "$bash_bin" "$repo/scripts/gallery-shots.sh" "$@"
    else
        set -- "PATH=$work/$stubs:$work/tools" HOME="$work" "PLAYWRIGHT_IMAGE=$pin" $extra_env "$bash_bin" "$repo/scripts/gallery-shots.sh" "$@"
    fi
    out="$(env -i "$@" 2>&1)" && code=0 || code=$?
}

# expected_argv <podman|docker> <plain|ci|update>: the run's argv, one per line.
expected_argv() {
    printf '%s\n' run --rm --platform linux/amd64 --network none --read-only \
        --tmpfs /tmp:rw,nosuid,size=2g --cap-drop ALL --security-opt no-new-privileges --init
    if [ "$1" = podman ]; then
        printf '%s\n' --userns=keep-id --http-proxy=false --no-hosts
    else
        printf '%s\n' --user "$(id -u):$(id -g)"
    fi
    printf '%s\n' \
        -v "$repo/frontend/ui/storybook-static:/work/frontend/ui/storybook-static:ro" \
        -v "$repo/frontend/ui/shots:/work/frontend/ui/shots:ro" \
        -v "$repo/frontend/ui/package.json:/work/frontend/ui/package.json:ro" \
        -v "$repo/frontend/node_modules:/work/frontend/node_modules:ro" \
        -v "$repo/frontend/ui/shots/output:/work/frontend/ui/shots/output:rw"
    if [ "$2" = update ]; then
        printf '%s\n' -v "$repo/frontend/ui/shots/__screenshots__:/work/frontend/ui/shots/__screenshots__:rw"
    fi
    printf '%s\n' -w /work/frontend/ui -e HOME=/tmp -e TZ=UTC -e "ZURFUR_GALLERY_IMAGE=$good_pin"
    if [ "$2" = ci ]; then
        printf '%s\n' -e CI=1
    fi
    printf '%s\n' "$image_ref" node /work/frontend/node_modules/@playwright/test/cli.js test \
        --config shots/playwright.config.ts
    if [ "$2" = update ]; then
        printf '%s\n' --update-snapshots=changed --project=stories
    else
        printf '%s\n' --update-snapshots=none
    fi
}

# expect_argv <name> <runtime> <podman|docker> <plain|ci|update>: the run
# exited 0, through <runtime>, with exactly that argv, and the script said
# which runtime and which flags it chose.
expect_argv() {
    want="$(expected_argv "$3" "$4")"
    got="$(cat "$work/log/run.argv" 2>/dev/null || echo '(no run)')"
    runtime="$(cat "$work/log/run.runtime" 2>/dev/null || echo '(none)')"
    line="gallery-shots: running in $2 ($3 flags)"
    if [ "$code" = 0 ] && [ "$runtime" = "$2" ] && [ "$got" = "$want" ] &&
        printf '%s\n' "$out" | grep -qxF -- "$line"; then
        ok "$1"
    else
        fail "$1" "exit $code, runtime $runtime; wanted the line '$line'; $out
--- argv got:
$got
--- argv wanted:
$want"
    fi
}

# expect_refused <name> <text>: exit 2, <text> in the output, and no run.
expect_refused() {
    if [ "$code" = 2 ] && printf '%s\n' "$out" | grep -qF -- "$2" && [ ! -f "$work/log/run.argv" ]; then
        ok "$1"
    else
        fail "$1" "exit $code, ran: $([ -f "$work/log/run.argv" ] && echo yes || echo no); $out"
    fi
}

# expect_untouched <name>: the runtime was never called.
expect_untouched() {
    if [ ! -f "$work/log/calls" ]; then ok "$1"; else fail "$1" "calls: $(cat "$work/log/calls")"; fi
}

