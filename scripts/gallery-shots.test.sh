# png <path> <width bytes> <height bytes> [pad to size]: a PNG signature and IHDR.
png() {
    printf '\211PNG\r\n\032\n\000\000\000\015IHDR'"$2$3"'\010\006\000\000\000' >"$1"
    if [ -n "${4-}" ]; then
        head -c "$(($4 - 29))" /dev/zero >>"$1"
    fi
}
