    "$prefix/light.png: a symlink"
walk_case "a symlinked folder fails the walk" "ln -s '$work/outside' more" "$prefix/more: a symlink"
walk_case "a FIFO fails the walk" "mkfifo light.png" "$prefix/light.png: not a regular file or folder"
walk_case "a .txt fails the walk" "png notes.txt '$one' '$one'" "$prefix/notes.txt: not named *.png"
walk_case "a dotfile fails the walk" "png .hidden '$one' '$one'" "$prefix/.hidden: not named *.png"
walk_case "1 MiB + 1 byte fails the walk" "png light.png '$one' '$one' 1048577" "$prefix/light.png: 1048577 bytes, over 1 MiB"
walk_case "a wrong signature fails the walk" "printf 'GIF89a\\000\\000\\000\\015IHDR\\000\\000\\000\\001\\000\\000\\000\\001xxxxx' >light.png" \
    "$prefix/light.png: not a PNG (wrong signature)"
walk_case "a PNG without IHDR first fails the walk" \
    "printf '\\211PNG\\r\\n\\032\\n\\000\\000\\000\\015IDAT\\000\\000\\000\\001\\000\\000\\000\\001xxxxx' >light.png" \
    "$prefix/light.png: not a PNG (no IHDR chunk first)"
walk_case "a file shorter than a PNG header fails the walk" "printf '\\211PNG\\r\\n\\032\\n' >light.png" \
    "$prefix/light.png: shorter than a PNG header"
walk_case "a 4097-px-wide PNG fails the walk" "png light.png '$side4097' '$one'" "$prefix/light.png: 4097x1 px, over 4096 px a side"
walk_case "a 4097-px-tall PNG fails the walk" "png light.png '$one' '$side4097'" "$prefix/light.png: 1x4097 px, over 4096 px a side"

