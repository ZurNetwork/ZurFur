/// The applied jacquard OAuth client this crate drives, over the
/// Postgres-backed [`AtprotoAuthStore`]. Private, so the protocol type never
/// appears in a public signature.
type Oauth = Arc<OAuthClient<JacquardResolver<reqwest::Client>, AtprotoAuthStore>>;

/// The real [`Authenticator`]: an OAuth client that talks to the visitor's PDS.
pub struct AtprotoAuthenticator {
    oauth: Oauth,
}

impl AtprotoAuthenticator {
    /// Build the loopback OAuth authenticator with `redirect_uri` as its sole
    /// registered redirect target. `pool` backs the persistent
    /// [`AtprotoAuthStore`]; `vault` seals that store's secrets at rest.
    pub fn new(redirect_uri: Uri<String>, pool: PgPool, vault: SecretVault) -> Self {
        Self {
            oauth: build_oauth(redirect_uri, AtprotoAuthStore::new(pool, vault)),
        }
    }
}

#[async_trait]
impl Authenticator for AtprotoAuthenticator {
    /// Resolve `handle` to its PDS, run a Pushed Authorization Request (the
    /// PKCE verifier and DPoP key are persisted under `state`), and return the
    /// PDS authorization URL. Errors if the handle or PDS is unreachable.
    async fn start(&self, handle: &str) -> anyhow::Result<String> {
        Ok(self
            .oauth
            .start_auth(handle, AuthorizeOptions::<jacquard::DefaultStr>::default())
            .await?)
    }

    /// Exchange the callback params for tokens, persist the established
    /// session, and return the session's verified `account_did`.
    /// Errors on an unknown/expired `state`, a failed `iss` check, or a failed
    /// token exchange.
    async fn complete(
        &self,
        code: String,
        state: Option<String>,
        iss: Option<String>,
    ) -> anyhow::Result<Did> {
        let params = CallbackParams {
            code: code.into(),
            state: state.map(Into::into),
            iss: iss.map(Into::into),
        };
        let session = self.oauth.callback(params).await?;
        let did = session.data.read().await.account_did.clone();
        Ok(Did::new(did.to_string()))
    }
}

/// OAuth scopes requested at sign-in: the base `atproto` scope plus the
/// transitional `transition:generic` grant for the legacy XRPC surface.
const OAUTH_SCOPES: &str = "atproto transition:generic";

/// Build the loopback OAuth client with `redirect_uri` registered as its sole
/// redirect target — jacquard derives the loopback `client_id` from that list
/// and there is no per-request override.
fn build_oauth(redirect_uri: Uri<String>, store: AtprotoAuthStore) -> Oauth {
    let scopes = Scopes::new(SmolStr::new_static(OAUTH_SCOPES))
        .expect("valid scopes")
        .convert();
    let config = AtprotoClientMetadata::new_localhost(Some(vec![redirect_uri]), Some(scopes));
    Arc::new(OAuthClient::new(
        store,
        ClientData {
            keyset: None,
            config,
        },
        reqwest::Client::new(),
    ))
}
